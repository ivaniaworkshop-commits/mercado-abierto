function originGuard(input){
 const parsed=new URL(input);
 assert(['http:','https:'].includes(parsed.protocol),'Only HTTP loopback or HTTPS preview are allowed');
 const host=parsed.hostname.toLowerCase();
 const local=['localhost','127.0.0.1','::1','[::1]'].includes(host);
 const preview=host.endsWith('.vercel.app') && host!=='rio-pey-codi-gateway.vercel.app' && host!=='rio-pey-codi-gateway-ivaniaworkshop-6855.vercel.app';
 assert(!parsed.username && !parsed.password && parsed.pathname==='/' && !parsed.search && !parsed.hash,'Origin must be a bare URL, without embedded credentials, query or fragment');
 if(preview){
  const approved=process.env.RIO_A11Y_APPROVED_PREVIEW_ORIGIN;
  assert(approved && new URL(approved).origin===parsed.origin,'Preview must exactly match independently verified RIO_A11Y_APPROVED_PREVIEW_ORIGIN');
  assert(/^[0-9a-f]{40}$/i.test(process.env.RIO_A11Y_SOURCE_SHA||''),'Preview requires its verified 40-hex source commit SHA');
 }
 assert(local||preview,'Refusing production or unknown origin; use an isolated loopback app or a verified preview URL');
 assert(local||parsed.protocol==='https:','Preview requires HTTPS');
 return parsed;
}
function allowAuditRequest(method,origin,pathname,target){
 return origin===target && (['GET','HEAD','OPTIONS'].includes(method) || (method==='POST' && pathname==='/v1/auth/login'));
}
async function login(page){
 await page.goto(report.target+'/',{waitUntil:'domcontentloaded'});
 assert.equal(new URL(page.url()).origin,report.target,'Unexpected cross-origin redirect before login; refusing to submit credentials');
 if(await page.locator('#dashboard:visible').count())return;
 const loginForm=page.locator('#login:visible');
 if(!await loginForm.count())throw Error('Authenticated app not reached (SSO, backend or route blocked).');
 const email=process.env.RIO_A11Y_LOGIN_EMAIL,password=process.env.RIO_A11Y_LOGIN_PASSWORD;
 if(!email||!password)throw Error('No authenticated session: provide a private storageState or login environment variables.');
 await loginForm.locator('input[name="email"]').fill(email);
 await loginForm.locator('input[name="password"]').fill(password);
 await page.locator('#login-submit:not([disabled])').click();
 await page.locator('[data-workspace-panel="menu"]:visible').waitFor({timeout:20000});
 assert.equal(new URL(page.url()).origin,report.target,'Unexpected cross-origin redirect after login');
}
const contrastJs=()=>{
 const rgba=s=>{
  if(s==='transparent')return [0,0,0,0];
  const m=String(s).match(/^rgba?\((.+)\)$/i);
  if(!m)return null;
  const v=m[1].replaceAll(',', ' ').replace('/',' ').trim().split(/\s+/).map(Number);
  if(v.length<3||v.some(x=>!Number.isFinite(x)))return null;
  return [v[0],v[1],v[2],v.length>3?v[3]:1];
 };
 const merge=(front,back)=>front.slice(0,3).map((v,i)=>v*front[3]+back[i]*(1-front[3]));
 const lum=c=>{
  const rgb=c.map(v=>{v=v/255;return v<=0.04045?v/12.92:Math.pow((v+0.055)/1.055,2.4);});
  return rgb[0]*0.2126+rgb[1]*0.7152+rgb[2]*0.0722;
 };
 const results=[],unknown=[],seen=new Set();
 const walker=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT);
 for(let text; (text=walker.nextNode());){
  if(!text.nodeValue.trim())continue;
  const el=text.parentElement;
  if(!el || !el.getClientRects().length)continue;
  const cs=getComputedStyle(el);
  if(cs.display==='none'||cs.visibility!=='visible')continue;
  const chain=[];let uncertain='';
  for(let node=el;node;node=node.parentElement){
   const css=getComputedStyle(node);
   if(css.display==='none'||css.visibility!=='visible'){uncertain='invisible ancestor';break;}
   if(css.backgroundImage!=='none'||css.mixBlendMode!=='normal'||Number(css.opacity)<1){
    uncertain='gradient/image/blend/opacity at '+node.tagName.toLowerCase();
   }
   const bg=rgba(css.backgroundColor);
   if(!bg){uncertain='unknown background '+css.backgroundColor;break;}
   chain.push(bg);
  }
  const label=el.id?'#'+el.id:el.tagName.toLowerCase();
  if(uncertain){unknown.push({element:label,reason:uncertain});continue;}
  let background=[255,255,255];
  for(const bg of chain.reverse())background=merge(bg,background);
  const foreground=rgba(cs.color);
  if(!foreground){unknown.push({element:label,reason:'unknown foreground '+cs.color});continue;}
  const color=merge(foreground,background);
  const ratio=(Math.max(lum(color),lum(background))+0.05)/(Math.min(lum(color),lum(background))+0.05);
  const key=cs.color+' on '+background.map(v=>Math.round(v)).join(',');
  if(!seen.has(key)){seen.add(key);results.push({foreground:cs.color,background:background.map(v=>Math.round(v)),ratio:Number(ratio.toFixed(3)),example:label});}
 }
 return {combinations:results,violations:results.filter(x=>x.ratio<4.5),unknown,threshold:4.5,
  method:'Computed CSS on visible direct text; composited solid ancestor backgrounds; gradients and overlays marked UNKNOWN.'};
};
